static struct wl_buffer *make_buffer(struct app *app, int w, int h, uint32_t color)
{
    int size = w * h * 4;
    int fd = memfd_create("sevyn-m1-shm", MFD_CLOEXEC);
    if (fd < 0) {
        log_line("M1CLIENT error: memfd_create failed: %s", strerror(errno));
        return NULL;
    }
    if (ftruncate(fd, size) < 0) {
        log_line("M1CLIENT error: ftruncate failed: %s", strerror(errno));
        close(fd);
        return NULL;
    }
    uint32_t *pixels = mmap(NULL, (size_t)size, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
    if (pixels == MAP_FAILED) {
        log_line("M1CLIENT error: mmap failed: %s", strerror(errno));
        close(fd);
        return NULL;
    }
    for (int i = 0; i < w * h; i++)
        pixels[i] = color;
    munmap(pixels, (size_t)size);
    struct wl_shm_pool *pool = wl_shm_create_pool(app->shm, fd, size);
    struct wl_buffer *buf = wl_shm_pool_create_buffer(pool, 0, w, h, w * 4, WL_SHM_FORMAT_XRGB8888);
    wl_shm_pool_destroy(pool);
    close(fd);
    return buf;
}

static void surface_commit(struct app *app, struct surface *s)
{
    if (!s->buffer) {
        if (mode_is("browser") && s == &app->toplevel_surface) {
            /* Two bands: chrome (top 152 px) vs content. The harness
             * tells them apart by pointer-enter coordinates, not by
             * colour, but distinct bands keep a future screendump
             * proof honest too. */
            int size = s->w * s->h * 4;
            int fd = memfd_create("sevyn-browser-shm", MFD_CLOEXEC);
            if (fd >= 0 && ftruncate(fd, size) == 0) {
                uint32_t *pixels = mmap(NULL, (size_t)size, PROT_READ | PROT_WRITE,
                                        MAP_SHARED, fd, 0);
                if (pixels != MAP_FAILED) {
                    for (int y = 0; y < s->h; y++) {
                        uint32_t color = (y < BROWSER_CHROME_H) ? 0xFF404040 : 0xFF182818;
                        for (int x = 0; x < s->w; x++)
                            pixels[y * s->w + x] = color;
                    }
                    munmap(pixels, (size_t)size);
                    struct wl_shm_pool *pool = wl_shm_create_pool(app->shm, fd, size);
                    s->buffer = wl_shm_pool_create_buffer(pool, 0, s->w, s->h, s->w * 4,
                                                           WL_SHM_FORMAT_XRGB8888);
                    wl_shm_pool_destroy(pool);
                }
                close(fd);
            }
            if (!s->buffer)
                return;
        } else {
            s->buffer = make_buffer(app, s->w, s->h, s->color);
        }
    }
    if (!s->buffer)
        return;
    wl_surface_attach(s->wl, s->buffer, 0, 0);
    wl_surface_damage(s->wl, 0, 0, s->w, s->h);
    wl_surface_commit(s->wl);
}

/* Stage 4 (chromium mode): recreate a surface's buffer at a new size.
 * The compositor's resize configure is honoured, not ignored. */
static void surface_resize(struct app *app, struct surface *s, int w, int h)
{
    if (s->buffer) {
        wl_buffer_destroy(s->buffer);
        s->buffer = NULL;
    }
    s->w = w;
    s->h = h;
    surface_commit(app, s);
}

/* --- presentation-time feedback --- */

/* Stage 3: the client asks for presentation-time feedback on its
 * toplevel surface and logs the `presented` event. That is the
 * client-side proof that worker 2's `send_presentation_feedback`
 * reaches a client: the compositor only sends feedback for a frame
 * that was actually presented. A `discarded` event is logged too
 * (the check treats "presented, never discarded" as the pass). The
 * listener must define every event: libwayland aborts on a NULL
 * entry for an event the compositor sends (same lesson as
 * keyboard repeat_info / pointer frame). */
static void presentation_feedback_presented(
    void *data, struct wp_presentation_feedback *feedback,
    uint32_t tv_sec_hi, uint32_t tv_sec_lo, uint32_t tv_nsec,
    uint32_t refresh, uint32_t seq_hi, uint32_t seq_lo, uint32_t flags)
{
    struct app *app = data;
    (void)feedback;
    (void)tv_sec_hi;
    (void)tv_sec_lo;
    (void)tv_nsec;
    (void)refresh;
    (void)flags;
    app->presentation_presented = true;
    log_line("PRESENTATION presented seq=%u.%u", seq_hi, seq_lo);
    wp_presentation_feedback_destroy(feedback);
    app->feedback = NULL;
}

static void presentation_feedback_discarded(void *data, struct wp_presentation_feedback *feedback)
{
    struct app *app = data;
    (void)feedback;
    log_line("PRESENTATION discarded");
    wp_presentation_feedback_destroy(feedback);
    app->feedback = NULL;
}

static void presentation_feedback_sync_output(void *data, struct wp_presentation_feedback *feedback,
                                              struct wl_output *output)
{
    (void)data;
    (void)feedback;
    (void)output;
}

static const struct wp_presentation_feedback_listener presentation_feedback_listener = {
    .sync_output = presentation_feedback_sync_output,
    .presented = presentation_feedback_presented,
    .discarded = presentation_feedback_discarded,
};

static void request_presentation_feedback(struct app *app)
{
    if (!app->presentation || app->feedback)
        return;
    app->feedback = wp_presentation_feedback(app->presentation, app->toplevel_surface.wl);
    if (app->feedback)
        wp_presentation_feedback_add_listener(app->feedback, &presentation_feedback_listener, app);
}

/* --- xdg_surface / toplevel --- */

static void xdg_surface_configure(void *data, struct xdg_surface *xdg_surface, uint32_t serial)
{
    struct app *app = data;
    xdg_surface_ack_configure(xdg_surface, serial);
    if (!app->configured) {
        app->configured = true;
        /* Ask for presentation feedback BEFORE the commit: Smithay
         * stores the request in the surface's pending state and the
         * commit moves it to current, so the frame this commit
         * produces is the one the feedback reports on. Requesting
         * after the commit would leave it pending until the NEXT
         * commit — and this client rarely commits twice. */
        request_presentation_feedback(app);
        surface_commit(app, &app->toplevel_surface);
        if (mode_is_m1()) {
            surface_commit(app, &app->left);
            surface_commit(app, &app->right);
        }
        if (mode_is("browser")) {
            log_line("BROWSER READY rect=0,%d,%d,348 size=%dx%d app_id=%s",
                     BROWSER_CHROME_H, BROWSER_WIN_W, win_w(), win_h(), mode_app_id());
        } else if (mode_is("chromium")) {
            log_line("CHROMIUM READY size=%dx%d app_id=%s", win_w(), win_h(), mode_app_id());
        } else if (mode_is("pointer-lock")) {
            log_line("POINTERLOCK READY size=%dx%d app_id=%s", win_w(), win_h(), mode_app_id());
        } else if (mode_is("clipboard-copy") || mode_is("clipboard-paste")) {
            log_line("CLIPBOARD READY role=%s size=%dx%d app_id=%s",
                     mode_is("clipboard-copy") ? "copy" : "paste",
                     win_w(), win_h(), mode_app_id());
        } else {
            log_line("M1CLIENT READY surfaces=A(left) B(right) size=%dx%d app_id=%s", WIN_W, WIN_H,
                     client_app_id());
        }
    } else {
        request_presentation_feedback(app);
        surface_commit(app, &app->toplevel_surface);
        if (mode_is_m1()) {
            surface_commit(app, &app->left);
            surface_commit(app, &app->right);
        }
    }
}

static const struct xdg_surface_listener xdg_surface_listener = {
    .configure = xdg_surface_configure,
};

static void xdg_toplevel_configure(void *data, struct xdg_toplevel *toplevel,
                                   int32_t width, int32_t height, struct wl_array *states)
{
    struct app *app = data;
    (void)toplevel;
    (void)states;
    if (mode_is("chromium")) {
        /* The Chromium stand-in honours compositor resizes: a nonzero
         * configure is the resize the adoption harness asserts (bridge
         * resize -> xdg_toplevel.configure -> client resizes). A 0x0
         * configure is the compositor's initial "no size" configure
         * and is ignored — the READY commit already drew 800x348. */
        log_line("CHROMIUM CONFIGURE size=%dx%d", width, height);
        if (width > 0 && height > 0 &&
            (width != app->toplevel_surface.w || height != app->toplevel_surface.h)) {
            surface_resize(app, &app->toplevel_surface, width, height);
            log_line("CHROMIUM RESIZED %dx%d", width, height);
        }
        return;
    }
    log_line("M1CLIENT toplevel configure size=%dx%d states=%d", width, height,
             (int)(states ? states->size / sizeof(uint32_t) : 0));
    /* M1 keeps its fixed 800x300 geometry; the harness measures the real
     * geometry from pointer-enter events, so a compositor resize would not
     * break the proof. */
}

static void xdg_toplevel_close(void *data, struct xdg_toplevel *toplevel)
{
    (void)data;
    (void)toplevel;
    log_line("M1CLIENT toplevel close requested, exiting");
    exit(0);
}

static const struct xdg_toplevel_listener xdg_toplevel_listener = {
    .configure = xdg_toplevel_configure,
    .close = xdg_toplevel_close,
};

