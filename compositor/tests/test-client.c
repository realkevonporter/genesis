/* Request the lock once the pointer is over our surface (the protocol
 * lets the compositor ignore a lock for a surface without pointer
 * focus, so the request is made on enter, not at startup). */
static void request_pointer_lock(struct app *app)
{
    if (!mode_is("pointer-lock") || app->lock_requested)
        return;
    app->lock_requested = true;
    if (!app->constraints || !app->relative_manager || !app->pointer) {
        log_line("POINTERLOCK error: missing pointer-constraints or relative-pointer globals (constraints=%d relative=%d pointer=%d)",
                 !!app->constraints, !!app->relative_manager, !!app->pointer);
        return;
    }
    app->locked_pointer = zwp_pointer_constraints_v1_lock_pointer(
        app->constraints, app->toplevel_surface.wl, app->pointer, NULL,
        ZWP_POINTER_CONSTRAINTS_V1_LIFETIME_ONESHOT);
    if (!app->locked_pointer) {
        log_line("POINTERLOCK error: lock_pointer returned NULL");
        return;
    }
    zwp_locked_pointer_v1_add_listener(app->locked_pointer, &locked_pointer_listener, app);
    app->relative_pointer = zwp_relative_pointer_manager_v1_get_relative_pointer(
        app->relative_manager, app->pointer);
    if (app->relative_pointer) {
        zwp_relative_pointer_v1_add_listener(app->relative_pointer,
                                             &relative_pointer_listener, app);
    }
    log_line("POINTER LOCK REQUESTED");
}
