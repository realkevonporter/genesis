/* SevynOS v2 M1 — compositor test client.
 *
 * One xdg_toplevel window (800x300) holding two subsurfaces side by side
 * (400x300 each, distinct dark colours). It is the click-target proof for
 * M1: every pointer enter/leave/button and every key event is logged with
 * the surface it landed on, so the host harness can sweep the pointer
 * across the screen and assert the compositor routes events to the surface
 * actually under the cursor.
 *
 * Logs go to /dev/console (the host harness reads the serial stream) and
 * to /tmp/sevyn-m1-client.log. Lines are prefixed with monotonic ms.
 *
 * Stage 3: SEVYN_CLIENT_APP_ID / SEVYN_CLIENT_TITLE / SEVYN_CLIENT_LOG
 * let one binary stand in for two surfaces (Shell + app) with distinct
 * identities and log files; defaults are the M1 values. The client also
 * binds wp_presentation when advertised and logs the `presented` event
 * for the frame its first commit produces (the presentation-time proof).
 *
 * Stage 4: SEVYN_CLIENT_MODE selects an adoption-test role (see
 * client_mode()): unset is the M1 behaviour; `browser` is the Browser
 * app stand-in (800x500 window, 152 px chrome + content rect
 * (0,152,800,348), app_id sevyn.browser); `chromium` is the Chromium
 * stand-in (800x348 window, app_id chromium, honours toplevel
 * configure resizes and logs CHROMIUM RESIZED); `clipboard-copy` /
 * `clipboard-paste` exercise wl_data_device copy/paste between two
 * clients; `pointer-lock` exercises zwp_pointer_constraints_v1 +
 * zwp_relative_pointer_manager_v1. The manager-bind mode is NOT here:
 * it belongs to the manager track. The bridge-socket client is the
 * harness's Python helper (bridge.py, generated by adoption-check.sh),
 * not a C mode — the harness needs request/response + event listening,
 * which is a poor fit for this client.
 *
 * Pointer-constraints / relative-pointer need generated protocol
 * headers (unstable XMLs); they are compiled in only when
 * SEVYN_HAVE_POINTER_CONSTRAINTS is defined (adoption-check.sh's
 * build defines it; nested-check.sh's build does not, so the plain
 * build keeps working). Clipboard uses the core wl_data_device
 * protocol (<wayland-client-protocol.h>), so it needs no generation.
 *
 * Build: gcc with wayland-client; xdg-shell + presentation-time protocol
 * sources are generated at build time by wayland-scanner (see
 * v2/image/build-m1-image.sh and compositor/tests/nested-check.sh).
 *
 * Stage 4: `--manager` mode (a separate entry point in this file, kept
 * in its own functions so the merge with the check track's adoption
 * modes stays clean) binds `zwlr_foreign_toplevel_manager_v1` (v2)
 * and `ext-foreign-toplevel-list-v1`, lists the open toplevels, and
 * exercises one manager request on a target app_id. It needs the wlr
 * + ext-list protocol sources generated at build time
 * (`wlr-foreign-toplevel-management-unstable-v1.xml` from the
 * wayland-protocols-wlr crate, `ext-foreign-toplevel-list-v1.xml`
 * from wayland-protocols) and `-DHAVE_WLR_FOREIGN_TOPLEVEL`;
 * without the define the default build is unchanged and `--manager`
 * prints an error. Env:
 *   SEVYN_MANAGER_TARGET_APP_ID  app_id to act on (unset = list only)
 *   SEVYN_MANAGER_ACTION         activate|close|minimize|unminimize|
 *                                maximize|unmaximize|fullscreen|
 *                                unfullscreen|none (default none)
 *   SEVYN_MANAGER_LOG            default /tmp/sevyn-manager-client.log
 *   SEVYN_MANAGER_LIST_WAIT_MS   ms to collect the listing (default 1500)
 *   SEVYN_MANAGER_ACTION_WAIT_MS ms to observe after the action
 *                                (default 1500)
 * Markers (same log file + console): `MANAGER TOPLEVEL app_id=..
 * title=.. state=..`, `MANAGER STATE ...`, `MANAGER CLOSED ...`,
 * `MANAGER ACTIVATE|CLOSE|MINIMIZE|MAXIMIZE|FULLSCREEN app_id=..`,
 * `LIST TOPLEVEL identifier=.. title=.. app_id=..`, `LIST CLOSED ...`,
 * `MANAGER DONE`.
 *
 * Window-raise fix: `--layer` mode (a separate entry point, same
 * pattern as `--manager`) binds `zwlr_layer_shell_v1`, creates one
 * fullscreen Background layer surface, and logs every pointer/keyboard
 * event it receives with a LAYER prefix — the proof that Genesis routes
 * input to layer surfaces. It needs the wlr layer-shell protocol
 * sources generated at build time
 * (`wlr-layer-shell-unstable-v1.xml` from the wayland-protocols-wlr
 * crate, `/usr/share/wayland-protocols` fallback) and
 * `-DHAVE_WLR_LAYER_SHELL`; without the define the default build is
 * unchanged and `--layer` prints an error. Env:
 *   SEVYN_LAYER_LOG        default /tmp/sevyn-layer-client.log
 *   SEVYN_LAYER_NAMESPACE  default "sevyn-test-layer"
 *   SEVYN_LAYER_WIDTH      default 1280
 *   SEVYN_LAYER_HEIGHT     default 800
 * Markers: `LAYER READY width=.. height=..` (first configure),
 * `LAYER CONFIGURE width=.. height=..` (every configure — the size is
 * corrected by a second configure after the first commit),
 * `LAYER PTR ENTER x=.. y=..`, `LAYER PTR BUTTON button=.. state=..`,
 * `LAYER KEY FOCUS`, `LAYER KEY key=.. state=..`, `LAYER CLOSED`.
 */
